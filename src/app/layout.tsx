import type { Metadata } from "next";
import { Suspense } from "react";
import { headers } from "next/headers";
import SessionWrapper from "@/components/SessionWrapper";
import GlobalLoader from "@/components/GlobalLoader";
import { ThemeProvider } from "@/components/ThemeProvider";

import "./globals.css";
import "@/styles/custom.css";

import Navbar from "@/components/Navbar";
import EmberField from "@/components/layout/EmberField";
import { Toaster } from "@/components/ui/sonner";

import { Newsreader, IBM_Plex_Mono, Literata } from "next/font/google";
import { cn } from "@/lib/utils";
import { SITE_URL } from "@/libs/site-url";

const fontDisplay = Newsreader({ subsets: ["latin"], variable: "--font-display" });
const fontBody = Literata({ subsets: ["latin"], variable: "--font-body" });
const fontMono = IBM_Plex_Mono({ subsets: ["latin"], weight: ["400", "500"], variable: "--font-mono" });

export const metadata: Metadata = {
    metadataBase: new URL(SITE_URL),
    title: "Vedev Blog",
    description: "Generated by vedev.guru",
    alternates: {
        types: { "application/rss+xml": "/feed.xml" },
    },
    icons: { apple: "/icons/apple-touch-icon.png" },
};

export default async function RootLayout({
    children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    // Set by proxy.ts; next-themes' inline theme script needs it to pass the CSP.
    const nonce = (await headers()).get("x-nonce") ?? undefined;
    return (
        <SessionWrapper>
            <html
                lang="en"
                className={cn("font-sans", fontDisplay.variable, fontBody.variable, fontMono.variable)}
                suppressHydrationWarning
            >
                <body>
                    <ThemeProvider attribute="class" defaultTheme="system" enableSystem disableTransitionOnChange nonce={nonce}>
                        <EmberField />
                        <Suspense fallback={null}>
                            <GlobalLoader />
                        </Suspense>
                        <Navbar />
                        {children}
                        <Toaster />
                    </ThemeProvider>
                </body>
            </html>
        </SessionWrapper>
    );
}
